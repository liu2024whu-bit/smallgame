import { motionAllowed } from '../../services/motion.js';

function returnGhost(gesture) {
  if(!gesture.ghost||!gesture.source?.isConnected||!motionAllowed())return;
  const from=gesture.ghost.getBoundingClientRect(),to=gesture.source.getBoundingClientRect();
  const ghost=gesture.ghost.cloneNode(true);
  gesture.ghost.parentElement.append(ghost);
  const dx=to.left+to.width/2-from.left-from.width/2,dy=to.top+to.height/2-from.top-from.height/2;
  const remove=()=>{window.clearTimeout(timer);ghost.remove();};
  const timer=window.setTimeout(remove,260);
  ghost.animate([{translate:'0 0',opacity:.85},{translate:`${dx}px ${dy}px`,scale:'.7',opacity:0}],{duration:180,easing:'ease-out',fill:'forwards'}).finished.catch(()=>{}).finally(remove);
}

// A gesture never changes saved state until release. Cancel and rerender are safe.
export function pointerSession(root, handlers) {
  const controller = new AbortController();
  const options = { signal: controller.signal };
  let gesture,pending;
  // Browser text/image drags must not take over an explicit puzzle gesture.
  root.addEventListener('dragstart',event=>{if(gesture)event.preventDefault();},options);
  function clear(current,cancelled){
    if(cancelled||current.returnToSource)returnGhost(current);
    current.ghost?.remove();root.classList.remove('is-dragging');handlers.clear?.(current,cancelled);
  }
  function finish(event, cancelled = false) {
    if (!gesture) return;
    const current = gesture;
    // A resize event can arrive after pointerup. A changed coordinate space
    // still cancels the gesture before saved state can be committed.
    cancelled ||= current.viewportWidth!==window.innerWidth||current.viewportHeight!==window.innerHeight;
    gesture = null;
    if(current.dragging)root.dataset.suppressUntil=Date.now()+350;
    const release=()=>{pending=null;try{if(current.dragging)handlers.end?.(current,event,cancelled);}finally{clear(current,cancelled);}};
    // Keep the original target connected until Chromium delivers touchend.
    // Replacing it during pointerup can suppress the following native tap.
    if(current.dragging&&!cancelled&&event?.pointerType==='touch')pending={current,timer:window.setTimeout(release,0)};
    else release();
  }
  root.addEventListener('pointerdown', event => {
    if (event.button !== 0 || !event.isPrimary || gesture || pending) return;
    // A fresh press is intentional. Only the click generated by the old drag is suppressed.
    delete root.dataset.suppressUntil;
    const picked = handlers.pick(event);
    if (!picked) return;
    gesture = { ...picked, x: event.clientX, y: event.clientY, pointer: event.pointerId, dragging: false, viewportWidth:window.innerWidth, viewportHeight:window.innerHeight };
  }, options);
  window.addEventListener('pointermove', event => {
    if (!gesture || event.pointerId !== gesture.pointer) return;
    if (!gesture.dragging && Math.hypot(event.clientX - gesture.x, event.clientY - gesture.y) < 5) return;
    event.preventDefault();
    if (!gesture.dragging) {
      gesture.dragging = true;
      root.classList.add('is-dragging');
      handlers.start?.(gesture, event);
    }
    handlers.move?.(gesture, event);
  }, { ...options, passive: false });
  window.addEventListener('pointerup', event => { if (gesture?.pointer === event.pointerId) finish(event); }, options);
  window.addEventListener('pointercancel', event => { if (gesture?.pointer === event.pointerId) finish(event, true); }, options);
  window.addEventListener('blur', event => finish(event, true), options);
  document.addEventListener('visibilitychange',event=>{if(document.hidden)finish(event,true);},options);
  window.addEventListener('resize', event => finish(event, true), options);
  window.addEventListener('keydown', event => {
    if (!gesture && ['Enter', ' '].includes(event.key)) delete root.dataset.suppressUntil;
    if (!gesture?.dragging) return;
    if (event.key === 'Escape') { event.preventDefault(); event.stopImmediatePropagation(); finish(event, true); }
    else handlers.key?.(gesture, event);
  }, { ...options, capture: true });
  return () => {
    if(pending){window.clearTimeout(pending.timer);clear(pending.current,true);pending=null;}
    finish(null,true);controller.abort();
  };
}

export function dragGhost(source, className = '') {
  const ghost = document.createElement('div');
  ghost.className = `drag-ghost ${className}`;
  ghost.innerHTML = typeof source === 'string' ? source : source.innerHTML;
  ghost.setAttribute('aria-hidden', 'true');
  (document.querySelector('dialog[open]') ?? document.body).append(ghost);
  return ghost;
}
